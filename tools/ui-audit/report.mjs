#!/usr/bin/env node
// Turns results-<label>.json into report/SUMMARY.md (committed) and a screenshot index under
// report/screenshots/<label>/ (git-ignored).
//
//   node report.mjs [--label=after] [--baseline=before]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, 'report');
const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, '').split('=')));
const label = args.label ?? 'latest';
const baselineLabel = args.baseline;
const load = (l) => JSON.parse(fs.readFileSync(path.join(OUT, `results-${l}.json`), 'utf8'));

export const CATEGORIES = [
  ['loadError', 'Load errors (timeout / HTTP 5xx)'],
  ['docOverflow', 'Horizontal page overflow'],
  ['overflowing', 'Elements overflowing the viewport'],
  ['clipped', 'Clipped text (overflow hidden, no ellipsis)'],
  ['tapSmallAA', 'Tap targets < 24px (WCAG 2.5.8 AA)'],
  ['tapSmall', 'Tap targets < 44px (design rule)'],
  ['unsizedImages', 'Images without size (layout shift risk)'],
  ['cls', 'Layout shift CLS > 0.1'],
  ['console', 'Console errors / hydration warnings'],
  ['axe', 'axe-core WCAG 2.2 AA violations'],
  ['contrast', '…of which colour contrast'],
  ['focus', 'Missing focus indicator'],
];

const norm = (s) => String(s ?? '').replace(/[0-9a-f]{8}-[0-9a-f-]{27}/g, ':id').replace(/\d+/g, '#');

/** Unique issues per app and category, with the page loads they occur on. */
export function analyse(data) {
  const by = {};
  const add = (app, cat, key, r, detail) => {
    by[app] ??= {};
    by[app][cat] ??= new Map();
    const m = by[app][cat];
    if (!m.has(key)) m.set(key, { key, detail, loads: 0, routes: new Set(), configs: new Set(), example: null });
    const e = m.get(key);
    e.loads++;
    e.routes.add(r.label);
    e.configs.add(r.config);
    e.example ??= { route: r.label, config: r.config, shot: r.shot };
  };
  const pages = {};
  for (const r of data.results) {
    pages[r.app] ??= { loads: 0, routes: new Set() };
    pages[r.app].loads++;
    pages[r.app].routes.add(r.label);
    if (r.error || (r.status && r.status >= 500)) add(r.app, 'loadError', `${r.label}`, r, r.error ?? `HTTP ${r.status}`);
    if (r.error) continue;
    if (r.docOverflow > 0) add(r.app, 'docOverflow', `${r.label}`, r, `${r.docOverflow}px wider at ${r.width}px`);
    for (const o of r.overflowing ?? []) add(r.app, 'overflowing', norm(o.sel), r, `${o.text || ''} (right edge ${o.right}px at ${o.vw}px)`);
    for (const o of r.clipped ?? []) add(r.app, 'clipped', norm(o.sel), r, `"${o.text}" (${o.axis} +${o.by}px)`);
    for (const o of r.tapSmallAA ?? []) add(r.app, 'tapSmallAA', norm(o.sel), r, `"${o.text}" ${o.w}×${o.h}`);
    for (const o of r.tapSmall ?? []) add(r.app, 'tapSmall', norm(o.sel), r, `"${o.text}" ${o.w}×${o.h}`);
    for (const o of r.unsizedImages ?? []) add(r.app, 'unsizedImages', norm(o.sel), r, o.src);
    if (r.cls > 0.1) add(r.app, 'cls', r.label, r, `CLS ${r.cls} (${(r.clsSources ?? []).join(', ')})`);
    for (const c of r.console ?? []) add(r.app, 'console', norm(c.text).slice(0, 160), r, c.text);
    for (const v of r.axe ?? []) {
      for (const t of v.targets.length ? v.targets : [{ target: '(page)' }]) {
        add(r.app, 'axe', `${v.id} ${norm(t.target)}`, r, `${v.id} (${v.impact}): ${t.summary || v.help}`);
        if (v.id === 'color-contrast') add(r.app, 'contrast', norm(t.target), r, t.summary || v.help);
      }
    }
    for (const f of r.focus?.missing ?? []) add(r.app, 'focus', norm(f.sel), r, f.text);
  }
  return { by, pages };
}

const count = (a, app, cat) => a.by[app]?.[cat]?.size ?? 0;
const loadsWith = (a, app, cat) => {
  const m = a.by[app]?.[cat];
  if (!m) return 0;
  return [...m.values()].reduce((s, e) => s + e.loads, 0);
};

function md(data, base) {
  const a = analyse(data);
  const b = base ? analyse(base) : null;
  const apps = data.meta.apps;
  const L = [];
  L.push(`# UI audit — ${data.meta.label}`);
  L.push('');
  L.push(`Generated by \`tools/ui-audit\` (${data.meta.mode} mode, ${data.results.length} page loads in ${Math.round(data.meta.seconds / 60)} min, Chromium ${'via Playwright'}).`);
  L.push('');
  L.push('Counts are **unique issues** (same element selector / same message / same axe rule+target collapse into one), so a header bug that appears on 150 pages counts once. "Loads" is how many page loads showed it.');
  L.push('');
  L.push('## Coverage');
  L.push('');
  L.push('| App | File-system routes | Visited URLs | Page loads | Not visited |');
  L.push('|---|---:|---:|---:|---|');
  for (const app of apps) {
    const c = data.meta.coverage[app] ?? {};
    L.push(`| ${app} | ${c.total ?? '?'} | ${a.pages[app]?.routes.size ?? 0} | ${a.pages[app]?.loads ?? 0} | ${(c.missing ?? []).map((m) => `\`${m}\``).join(', ') || '—'} |`);
  }
  L.push('');
  L.push(`Configurations: ${data.meta.configs.map((c) => `\`${c}\``).join(', ')}.`);
  L.push('');
  if (b) {
    L.push(`## Before / after (baseline: \`${base.meta.label}\`)`);
    L.push('');
    L.push(`| Category | ${apps.map((x) => `${x} before → after`).join(' | ')} |`);
    L.push(`|---|${apps.map(() => '---:').join('|')}|`);
    for (const [cat, title] of CATEGORIES) L.push(`| ${title} | ${apps.map((app) => `${count(b, app, cat)} → **${count(a, app, cat)}**`).join(' | ')} |`);
    L.push('');
    L.push(`| Affected page loads | ${apps.map((x) => `${x} before → after`).join(' | ')} |`);
    L.push(`|---|${apps.map(() => '---:').join('|')}|`);
    for (const [cat, title] of CATEGORIES) L.push(`| ${title} | ${apps.map((app) => `${loadsWith(b, app, cat)} → **${loadsWith(a, app, cat)}**`).join(' | ')} |`);
    L.push('');
  }
  L.push('## Totals');
  L.push('');
  L.push(`| Category | ${apps.join(' | ')} |`);
  L.push(`|---|${apps.map(() => '---:').join('|')}|`);
  for (const [cat, title] of CATEGORIES) L.push(`| ${title} | ${apps.map((app) => `${count(a, app, cat)} (${loadsWith(a, app, cat)} loads)`).join(' | ')} |`);
  L.push('');
  L.push('## Remaining issues by app');
  for (const app of apps) {
    L.push('');
    L.push(`### ${app}`);
    for (const [cat, title] of CATEGORIES) {
      const m = a.by[app]?.[cat];
      if (!m?.size) continue;
      L.push('');
      L.push(`<details><summary><strong>${title}</strong> — ${m.size}</summary>`);
      L.push('');
      L.push('| Issue | Detail | Loads | Example |');
      L.push('|---|---|---:|---|');
      for (const e of [...m.values()].sort((x, y) => y.loads - x.loads).slice(0, 25)) {
        L.push(`| \`${e.key.replace(/\|/g, '\\|').slice(0, 110)}\` | ${String(e.detail ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 140)} | ${e.loads} | ${e.example.route} @ ${e.example.config} |`);
      }
      if (m.size > 25) L.push(`| … | ${m.size - 25} more | | |`);
      L.push('');
      L.push('</details>');
    }
  }
  L.push('');
  return L.join('\n');
}

function shotIndex(data) {
  const dir = path.join(OUT, 'screenshots', data.meta.label);
  fs.mkdirSync(dir, { recursive: true });
  const L = [`# Screenshots — ${data.meta.label}`, ''];
  const H = [`<!doctype html><meta charset="utf-8"><title>UI audit screenshots — ${data.meta.label}</title><style>body{font:14px system-ui;margin:16px;background:#F3F2EE}h2{margin-top:32px}figure{display:inline-block;margin:6px;vertical-align:top;background:#fff;padding:6px;border-radius:12px}img{display:block;max-height:280px;max-width:240px}figcaption{font-size:11px}.bad{outline:3px solid #9E1B12}</style>`];
  for (const app of data.meta.apps) {
    L.push(`## ${app}`, '');
    H.push(`<h1>${app}</h1>`);
    const routes = new Map();
    for (const r of data.results.filter((x) => x.app === app)) {
      if (!routes.has(r.label)) routes.set(r.label, []);
      routes.get(r.label).push(r);
    }
    for (const [route, rs] of routes) {
      L.push(`- **${route}**: ${rs.filter((r) => r.shot).map((r) => `[${r.config}](../../${r.shot})`).join(' · ')}`);
      H.push(`<h2>${route}</h2>`);
      for (const r of rs.filter((x) => x.shot)) {
        const bad = r.docOverflow > 0 || (r.clipped ?? []).length || (r.overflowing ?? []).length;
        H.push(`<figure class="${bad ? 'bad' : ''}"><a href="../../${r.shot}"><img loading="lazy" src="../../${r.shot}"></a><figcaption>${r.config}${bad ? ' · overflow/clip' : ''}</figcaption></figure>`);
      }
    }
    L.push('');
  }
  fs.writeFileSync(path.join(dir, 'index.md'), L.join('\n'));
  fs.writeFileSync(path.join(dir, 'index.html'), H.join('\n'));
  return path.join(dir, 'index.html');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const data = load(label);
  const base = baselineLabel ? load(baselineLabel) : null;
  const file = path.join(OUT, label === 'latest' ? 'SUMMARY.md' : `SUMMARY-${label}.md`);
  fs.writeFileSync(file, md(data, base));
  const idx = shotIndex(data);
  console.log(`[ui-audit] wrote ${path.relative(process.cwd(), file)} and ${path.relative(process.cwd(), idx)}`);
}
