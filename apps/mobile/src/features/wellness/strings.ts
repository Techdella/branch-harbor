export const STRINGS: Record<string, typeof en> = { en, fr, es, de, 'pt-BR': ptBR };

export function useWT() {
  const { locale, intlLocale } = useI18n();
  const table = STRINGS[locale] ?? en;
  return {
    locale: intlLocale,
    t: (k: WKey, vars: Record<string, string | number> = {}) => (table[k] ?? en[k]).replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? '')),
  };
}
