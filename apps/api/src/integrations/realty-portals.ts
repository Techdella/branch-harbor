/**
 * Property-portal syndication adapters. Each adapter turns opted-in listings into the feed shape a portal family
 * expects and validates required fields. ALL adapters run in sandbox mode: feeds can be previewed and a sandbox
 * export is recorded, but nothing is transmitted and no portal account is connected. `live` is always false until a
 * real, contracted integration (credentials, endpoint, certification) exists — the UI must say so.
 */
import { formatAddressLines, fromSqm } from '@bh/shared';

export interface FeedListing {
  id: string;
  reference: string;
  transaction: 'sale' | 'rent';
  propertyType: string;
  status: string;
  title: string;
  description: string | null;
  address: { line1: string; line2: string | null; city: string; region: string | null; postalCode: string | null; country: string };
  hideStreet: boolean;
  geo: { lat: number; lng: number } | null;
  price: { amount: number; currency: string };
  rentPeriod: string | null;
  bedrooms: number | null;
  bathrooms: number | null;
  areaSqm: number | null;
  photos: Array<{ url: string; caption?: string | null }>;
  floorPlans: Array<{ url: string }>;
  virtualTourUrl: string | null;
  features: string[];
  agent: { name: string; email: string | null; phone: string | null } | null;
  office: { name: string; phone: string | null; brokerageLicence: string | null };
  disclosures: Array<{ label: string; text: string }>;
}

export interface PortalAdapter {
  id: 'zillow_style' | 'realtor_ca_style' | 'rightmove_style' | 'idealista_style';
  name: string;
  /** Feed family this adapter imitates; not an endorsement or a connection. */
  description: string;
  format: 'xml' | 'json';
  countries: string[];
  mode: 'sandbox';
  live: false;
  validate(l: FeedListing): string[];
  build(listings: FeedListing[], meta: { generatedAt: string; organization: string }): string;
}

const esc = (s: string | number | null | undefined) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const major = (m: { amount: number; currency: string }) => (m.currency === 'JPY' ? m.amount : m.amount / 100);
const common = (l: FeedListing) => {
  const issues: string[] = [];
  if (!l.photos.length) issues.push('At least one photo is required');
  if (!l.description || l.description.length < 50) issues.push('Description must be at least 50 characters');
  if (l.price.amount <= 0) issues.push('Price is required');
  if (!l.agent) issues.push('A listing agent is required');
  return issues;
};

const zillow: PortalAdapter = {
  id: 'zillow_style', name: 'Zillow-style XML', description: 'US listing feed layout (XML) used by Zillow-type portals', format: 'xml', countries: ['US'], mode: 'sandbox', live: false,
  validate: (l) => [...common(l), ...(l.address.country !== 'US' ? ['Only US listings fit this feed'] : []), ...(!l.address.postalCode ? ['ZIP code is required'] : [])],
  build: (ls, meta) => `<?xml version="1.0" encoding="UTF-8"?>\n<!-- SANDBOX FEED: generated by BranchHarbor for preview only; not transmitted. -->\n<Listings generated="${esc(meta.generatedAt)}" source="${esc(meta.organization)}">\n${ls.map((l) => `  <Listing>\n    <Location><StreetAddress>${esc(l.hideStreet ? '' : l.address.line1)}</StreetAddress><UnitNumber>${esc(l.address.line2)}</UnitNumber><City>${esc(l.address.city)}</City><State>${esc(l.address.region)}</State><Zip>${esc(l.address.postalCode)}</Zip>${l.geo && !l.hideStreet ? `<Lat>${l.geo.lat}</Lat><Long>${l.geo.lng}</Long>` : ''}</Location>\n    <ListingDetails><Status>${esc(l.status === 'under_offer' ? 'Pending' : l.status === 'coming_soon' ? 'Coming Soon' : 'Active')}</Status><Price currency="${esc(l.price.currency)}">${major(l.price)}</Price><ListingUrl/><MlsId>${esc(l.reference)}</MlsId></ListingDetails>\n    <BasicDetails><PropertyType>${esc(l.propertyType)}</PropertyType><Title>${esc(l.title)}</Title><Description>${esc(l.description)}</Description><Bedrooms>${esc(l.bedrooms)}</Bedrooms><Bathrooms>${esc(l.bathrooms)}</Bathrooms><LivingArea unit="sqft">${l.areaSqm ? Math.round(fromSqm(l.areaSqm, 'sqft')) : ''}</LivingArea></BasicDetails>\n    <Pictures>${l.photos.map((p) => `<Picture><PictureUrl>${esc(p.url)}</PictureUrl><Caption>${esc(p.caption)}</Caption></Picture>`).join('')}</Pictures>\n    <Agent><FirstName>${esc(l.agent?.name.split(' ')[0])}</FirstName><LastName>${esc(l.agent?.name.split(' ').slice(1).join(' '))}</LastName><EmailAddress>${esc(l.agent?.email)}</EmailAddress></Agent>\n    <Office><BrokerageName>${esc(l.office.name)}</BrokerageName><BrokerPhone>${esc(l.office.phone)}</BrokerPhone></Office>\n    ${l.virtualTourUrl ? `<VirtualTourUrl>${esc(l.virtualTourUrl)}</VirtualTourUrl>` : ''}\n  </Listing>`).join('\n')}\n</Listings>\n`,
};

const realtorCa: PortalAdapter = {
  id: 'realtor_ca_style', name: 'Realtor.ca-style JSON', description: 'Canadian board-feed layout (JSON) similar to DDF®-type exports', format: 'json', countries: ['CA'], mode: 'sandbox', live: false,
  validate: (l) => [...common(l), ...(l.address.country !== 'CA' ? ['Only Canadian listings fit this feed'] : []), ...(!l.office.brokerageLicence ? ['Brokerage name/licence disclosure is required'] : [])],
  build: (ls, meta) => JSON.stringify({
    sandbox: true, notice: 'Sandbox feed for preview only; not transmitted to any board or portal.', generatedAt: meta.generatedAt, source: meta.organization,
    listings: ls.map((l) => ({
      ListingKey: l.reference, StandardStatus: l.status, TransactionType: l.transaction === 'sale' ? 'For sale' : 'For rent', PropertySubType: l.propertyType,
      ListPrice: major(l.price), Currency: l.price.currency, LeasePeriod: l.rentPeriod, BedroomsTotal: l.bedrooms, BathroomsTotalInteger: l.bathrooms != null ? Math.floor(l.bathrooms) : null,
      LivingAreaSqFt: l.areaSqm ? Math.round(fromSqm(l.areaSqm, 'sqft')) : null, PublicRemarks: l.description,
      UnparsedAddress: formatAddressLines({ ...l.address }, { hideStreet: l.hideStreet }).join(', '), City: l.address.city, StateOrProvince: l.address.region, PostalCode: l.hideStreet ? null : l.address.postalCode,
      Media: l.photos.map((p, i) => ({ Order: i + 1, MediaURL: p.url, ShortDescription: p.caption ?? null })), VirtualTourURLUnbranded: l.virtualTourUrl,
      ListAgentFullName: l.agent?.name ?? null, ListOfficeName: l.office.name, BrokerageDisclosure: l.office.brokerageLicence,
    })),
  }, null, 2),
};

const rightmove: PortalAdapter = {
  id: 'rightmove_style', name: 'Rightmove-style JSON', description: 'UK real-time datafeed layout (JSON) used by Rightmove-type portals', format: 'json', countries: ['GB'], mode: 'sandbox', live: false,
  validate: (l) => [...common(l), ...(l.address.country !== 'GB' ? ['Only UK listings fit this feed'] : []), ...(!l.address.postalCode ? ['Postcode is required'] : []), ...(l.disclosures.length === 0 ? ['Material information (e.g. tenure, council tax band, EPC) supplied by the business is required'] : [])],
  build: (ls, meta) => JSON.stringify({
    sandbox: true, notice: 'Sandbox feed for preview only; not transmitted.', generatedAt: meta.generatedAt, network: meta.organization,
    properties: ls.map((l) => ({
      agent_ref: l.reference, published: true, property_type: l.propertyType, status: l.status === 'under_offer' ? (l.transaction === 'sale' ? 'Under Offer' : 'Let Agreed') : 'Available',
      channel: l.transaction === 'sale' ? 'sales' : 'lettings', price_information: { price: major(l.price), currency: l.price.currency, rent_frequency: l.rentPeriod },
      address: { house_name_number: l.hideStreet ? null : l.address.line1, address_2: l.address.line2, town: l.address.city, postcode_1: l.address.postalCode?.split(' ')[0] ?? null, postcode_2: l.hideStreet ? null : l.address.postalCode?.split(' ')[1] ?? null, display_address: formatAddressLines({ ...l.address }, { hideStreet: true }).join(', ') },
      details: { summary: l.title, description: l.description, bedrooms: l.bedrooms, bathrooms: l.bathrooms, internal_area: l.areaSqm ? Math.round(fromSqm(l.areaSqm, 'sqft')) : null, internal_area_unit: 'sq ft', features: l.features.slice(0, 10) },
      media: [...l.photos.map((p) => ({ media_type: 1, media_url: p.url, caption: p.caption ?? null })), ...l.floorPlans.map((p) => ({ media_type: 2, media_url: p.url })), ...(l.virtualTourUrl ? [{ media_type: 4, media_url: l.virtualTourUrl }] : [])],
      material_information: l.disclosures,
    })),
  }, null, 2),
};

const idealista: PortalAdapter = {
  id: 'idealista_style', name: 'Idealista-style XML', description: 'Southern-Europe portal layout (XML) used by Idealista-type portals', format: 'xml', countries: ['ES', 'PT', 'IT'], mode: 'sandbox', live: false,
  validate: (l) => [...common(l), ...(!['ES', 'PT', 'IT'].includes(l.address.country) ? ['Only Spain, Portugal and Italy listings fit this feed'] : []), ...(l.areaSqm == null ? ['Built area (m²) is required'] : []), ...(!l.disclosures.some((d) => /energ/i.test(d.label)) ? ['Energy certificate disclosure supplied by the business is required'] : [])],
  build: (ls, meta) => `<?xml version="1.0" encoding="UTF-8"?>\n<!-- SANDBOX FEED: preview only; not transmitted. -->\n<feed generated="${esc(meta.generatedAt)}" customer="${esc(meta.organization)}">\n${ls.map((l) => `  <property code="${esc(l.reference)}" operation="${l.transaction === 'sale' ? 'sale' : 'rent'}" type="${esc(l.propertyType)}">\n    <price currency="${esc(l.price.currency)}">${major(l.price)}</price>\n    <address visibility="${l.hideStreet ? 'hidden' : 'full'}"><street>${esc(l.hideStreet ? '' : l.address.line1)}</street><postalCode>${esc(l.address.postalCode)}</postalCode><town>${esc(l.address.city)}</town><province>${esc(l.address.region)}</province><country>${esc(l.address.country)}</country></address>\n    <features><areaConstructed unit="m2">${l.areaSqm ? Math.round(l.areaSqm) : ''}</areaConstructed><rooms>${esc(l.bedrooms)}</rooms><bathrooms>${esc(l.bathrooms)}</bathrooms></features>\n    <descriptions><description lang="es">${esc(l.description)}</description></descriptions>\n    <images>${l.photos.map((p, i) => `<image order="${i + 1}">${esc(p.url)}</image>`).join('')}</images>\n    <energyCertificate>${esc(l.disclosures.find((d) => /energ/i.test(d.label))?.text)}</energyCertificate>\n    <contact name="${esc(l.agent?.name)}" phone="${esc(l.office.phone)}"/>\n  </property>`).join('\n')}\n</feed>\n`,
};

export const PORTAL_ADAPTERS: Record<PortalAdapter['id'], PortalAdapter> = {
  zillow_style: zillow,
  realtor_ca_style: realtorCa,
  rightmove_style: rightmove,
  idealista_style: idealista,
};
export const PORTAL_IDS = Object.keys(PORTAL_ADAPTERS) as PortalAdapter['id'][];
